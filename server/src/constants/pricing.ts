export interface CatalogueEntry extends Omit<UsageMeter, 'quantity'> {
  match: RegExp;
  free?: Partial<MeterPricing>;
}

function entry(
  key: string,
  service: string,
  name: string,
  unit: string,
  match: RegExp,
  unitPrice: number,
  unitSize: number,
  includedQuantity: number,
  source: string,
  options: Pick<CatalogueEntry, 'free'> & {
    rounding?: 'up';
  } = {},
): CatalogueEntry {
  const { rounding, ...metadata } = options;
  return {
    key,
    service,
    name,
    unit,
    match,
    ...metadata,
    pricing: {
      currency: 'USD',
      unitPrice,
      unitSize,
      includedQuantity,
      allowancePeriod: 'cycle',
      source,
      ...(rounding ? { rounding } : {}),
    },
  };
}

